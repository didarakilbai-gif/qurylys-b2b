let currentLang = localStorage.getItem("qurylys_lang") || "kk";

function setLanguage(lang) {
    if (!I18N_DATA[lang]) return;
    currentLang = lang;
    localStorage.setItem("qurylys_lang", lang);

    const data = I18N_DATA[lang];

    // Барлық data-i18n элементтерін жаңарту
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (data[key]) {
            el.innerHTML = data[key];
        }
    });

    // Барлық placeholder элементтерін жаңарту
    document.querySelectorAll("[data-i18n-ph]").forEach(el => {
        const key = el.getAttribute("data-i18n-ph");
        if (data[key]) {
            el.setAttribute("placeholder", data[key]);
        }
    });

    const langSelect = document.getElementById("langSelect");
    if (langSelect) langSelect.value = lang;
}