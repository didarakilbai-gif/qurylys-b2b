function activateAntiScreenshot() {
    const shield = document.getElementById("blackoutShield");

    window.addEventListener("keyup", (e) => {
        if (e.key === "PrintScreen" || e.keyCode === 44) triggerBlackout();
    });

    window.addEventListener("keydown", (e) => {
        if ((e.ctrlKey || e.metaKey) && (e.key === "p" || e.key === "s")) {
            e.preventDefault();
            triggerBlackout();
        }
    });

    window.addEventListener("blur", () => { triggerBlackout(); });
    window.addEventListener("focus", () => { if (shield) shield.style.display = "none"; });

    document.addEventListener("visibilitychange", () => {
        if (document.hidden) triggerBlackout();
        else if (shield) shield.style.display = "none";
    });

    function triggerBlackout() {
        if (!shield) return;
        shield.style.display = "flex";
        setTimeout(() => { if (shield) shield.style.display = "none"; }, 1500);
    }
}

