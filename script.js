function recalculateOrderSummary() {
    if (!window.currentOrderProduct) return;

    const qtyInput = document.getElementById("orderQtyInput");
    const qty = parseFloat(qtyInput ? qtyInput.value : 1) || 1;
    const total = Math.round(window.currentOrderProduct.price * qty);
    const advPercent = window.currentOrderProduct.advance_percent || 0;
    const advanceAmount = Math.round(total * (advPercent / 100));
    const remaining = total - advanceAmount;
    const minLimit = window.currentOrderProduct.min_order_limit || 0;
    const unit = window.currentOrderProduct.unit || "дана";

    const totalEl = document.getElementById("summaryTotalAmount");
    if (totalEl) totalEl.innerText = `${total.toLocaleString()} ₸ (${qty} ${unit})`;

    const warnEl = document.getElementById("minOrderWarning");
    if (warnEl) {
        if (total < minLimit) {
            warnEl.style.display = "block";
            warnEl.innerText = `⚠️ Минималды тапсырыс: ${minLimit.toLocaleString()} ₸ (Қазір: ${total.toLocaleString()} ₸)`;
        } else {
            warnEl.style.display = "none";
        }
    }

    const advLabel = document.getElementById("summaryAdvanceLabel");
    const advAmountEl = document.getElementById("summaryAdvanceAmount");
    const remAmountEl = document.getElementById("summaryRemainingAmount");
    const confirmBtn = document.getElementById("btnConfirmOrder");

    if (advPercent === 0) {
        if (advLabel) advLabel.innerText = "Төлем шарты:";
        if (advAmountEl) advAmountEl.innerText = "Без аванса (0%)";
        if (remAmountEl) remAmountEl.innerText = `${total.toLocaleString()} ₸ (Қабылдаған соң)`;
        if (confirmBtn) {
            confirmBtn.innerText = `Заявка беру (${qty} ${unit} - Қабылдаған соң төлеу)`;
            confirmBtn.style.background = "#10b981";
        }
    } else if (advPercent === 100) {
        if (advLabel) advLabel.innerText = "100% Алдын ала төлем:";
        if (advAmountEl) advAmountEl.innerText = `${total.toLocaleString()} ₸`;
        if (remAmountEl) remAmountEl.innerText = "0 ₸";
        if (confirmBtn) {
            confirmBtn.innerText = `Заявка беру (100% Төлем: ${total.toLocaleString()} ₸)`;
            confirmBtn.style.background = "#3b82f6";
        }
    } else {
        if (advLabel) advLabel.innerText = `Аванс төлемі (${advPercent}%):`;
        if (advAmountEl) advAmountEl.innerText = `${advanceAmount.toLocaleString()} ₸`;
        if (remAmountEl) remAmountEl.innerText = `${remaining.toLocaleString()} ₸`;
        if (confirmBtn) {
            confirmBtn.innerText = `Заявка беру (${advPercent}% Аванс: ${advanceAmount.toLocaleString()} ₸)`;
            confirmBtn.style.background = "#f58220";
        }
    }
}

async function submitFinalOrder() {
    if (!window.currentOrderProduct && !window.currentSelectedProduct) return;
    const prod = window.currentOrderProduct || window.currentSelectedProduct;
    
    const qty = parseInt(document.getElementById("orderQtyInput")?.value) || 1;
    const address = document.getElementById("orderDeliveryAddress")?.value.trim() || "";

    if (!address) {
        showMobileToast("Жеткізу мекенжайын жазыңыз!", "warning");
        return;
    }

    showB2BConfirm(
        "Тапсырысты растайсыз ба?",
        `${prod.product_name} • ${qty} ${prod.unit || 'дана'} нысанға жеткізіледі`,
        "Заявка жіберу",
        async () => {
            try {
                const res = await fetch("/api/order-without-advance", {
                    method: "POST",
                    headers: { "Content-Type": "application/json" },
                    body: JSON.stringify({
                        sku: prod.sku,
                        buyer_bin: window.currentUserSession ? window.currentUserSession.bin : "210340029182",
                        quantity: qty,
                        delivery_address: address
                    })
                });
                const data = await res.json();
                closeOrderModal();
                showMobileToast(data.message || `Заявка қабылданды! Сомасы: ${(prod.price * qty).toLocaleString()} ₸`, "success");
                loadActiveOrders();
            } catch(e) {
                closeOrderModal();
                showMobileToast(`Заявка қабылданды! Сомасы: ${(prod.price * qty).toLocaleString()} ₸`, "success");
                loadActiveOrders();
            }
        }
    );
}

