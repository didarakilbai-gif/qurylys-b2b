function initOrUpdateMap() {
    if (typeof L === "undefined") return;
    const mapBox = document.getElementById("interactiveMapContainer");
    if (!mapBox) return;

    if (!window.leafletMapInstance) {
        window.leafletMapInstance = L.map("interactiveMapContainer").setView([43.2642, 76.8920], 12);
        L.tileLayer("https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png", {
            attribution: '© OpenStreetMap | Qurylys Logistics'
        }).addTo(window.leafletMapInstance);
        window.mapMarkersGroup = L.layerGroup().addTo(window.leafletMapInstance);
    } else {
        window.leafletMapInstance.invalidateSize();
    }

    renderMapMarkers("all");
}

function renderMapMarkers(filterType = "all") {
    if (!window.mapMarkersGroup || typeof L === "undefined") return;
    window.mapMarkersGroup.clearLayers();

    const filtered = filterType === "all" 
        ? window.LOGISTICS_POINTS 
        : window.LOGISTICS_POINTS.filter(p => p.type === filterType);

    filtered.forEach(point => {
        let color = point.type === "crossdock" ? "#10b981" : (point.type === "site" ? "#f59e0b" : "#3b82f6");

        const marker = L.circleMarker([point.lat, point.lon], {
            radius: 10,
            fillColor: color,
            color: "#ffffff",
            weight: 2,
            opacity: 1,
            fillOpacity: 0.9
        });

        marker.on("click", () => { selectMapPoint(point); });
        marker.bindTooltip(`<b>${point.name}</b>`, { direction: "top", offset: [0, -8] });
        window.mapMarkersGroup.addLayer(marker);
    });

    if (filtered.length > 0) selectMapPoint(filtered[0]);
}

