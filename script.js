function showMobileToast(text, type = "success") {
    let bgColor = "#10b981";
    if (type === "warning") bgColor = "#f59e0b";
    if (type === "error") bgColor = "#ef4444";
    if (type === "info") bgColor = "#0f5257";

    if (typeof Toastify !== "undefined") {
        Toastify({
            text: text,
            duration: 2500,
            gravity: "top",
            position: "center",
            stopOnFocus: true,
            style: {
                background: bgColor,
                color: "#ffffff",
                padding: "10px 16px",
                borderRadius: "10px",
                fontSize: "12.5px",
                fontWeight: "600",
                boxShadow: "0 4px 12px rgba(0,0,0,0.15)"
            }
        }).showToast();
    } else {
        alert(text);
    }
}

