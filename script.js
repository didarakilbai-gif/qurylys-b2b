function getFilteredProductsArray(pool) {
    const minVal = document.getElementById("filterMinPrice")?.value.trim() || "";
    const maxVal = document.getElementById("filterMaxPrice")?.value.trim() || "";
    const minPrice = minVal !== "" ? parseFloat(minVal) : 0;
    const maxPrice = maxVal !== "" ? parseFloat(maxVal) : Infinity;

    const adv0 = document.getElementById("filterAdv0")?.checked || false;
    const adv30 = document.getElementById("filterAdv30")?.checked || false;
    const adv50 = document.getElementById("filterAdv50")?.checked || false;
    const adv100 = document.getElementById("filterAdv100")?.checked || false;
    const hasAdvFilter = adv0 || adv30 || adv50 || adv100;

    const vatYes = document.getElementById("filterVatYes") ? document.getElementById("filterVatYes").checked : true;
    const vatNo = document.getElementById("filterVatNo") ? document.getElementById("filterVatNo").checked : true;

    const inStockOnly = document.getElementById("filterInStockOnly") ? document.getElementById("filterInStockOnly").checked : false;

    const selectedBrands = Array.from(document.querySelectorAll("input[name='filterBrandCheck']:checked")).map(el => el.value);
    const selectedUnits = Array.from(document.querySelectorAll("input[name='unitFilter']:checked")).map(el => el.value.toLowerCase());

    return pool.filter(p => {
        if (p.price < minPrice || p.price > maxPrice) return false;
        if (inStockOnly && p.stock <= 0) return false;
        if (p.has_vat && !vatYes) return false;
        if (!p.has_vat && !vatNo) return false;
        if (selectedBrands.length > 0 && !selectedBrands.includes(p.brandName)) return false;
        if (selectedUnits.length > 0 && !selectedUnits.includes(p.unit)) return false;

        if (hasAdvFilter) {
            let match = false;
            if (adv0 && p.advance_percent === 0) match = true;
            if (adv30 && p.advance_percent === 30) match = true;
            if (adv50 && p.advance_percent === 50) match = true;
            if (adv100 && p.advance_percent === 100) match = true;
            if (!match) return false;
        }

        return true;
    });
}

